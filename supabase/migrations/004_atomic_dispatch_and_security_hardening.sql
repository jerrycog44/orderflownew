-- ----------------------------------------------------------------------------
-- Permissive policies are OR-ed together, so every policy granting provider
-- visibility must be reviewed as a set. After this section, a provider can
-- read a raw delivery / package row ONLY when provider_id = auth.uid().
-- Prospective providers use get_marketplace_opportunities() instead.

-- 11a. Remove migration 003 marketplace policies (exposed PII to all providers)
DROP POLICY IF EXISTS "Providers can view open marketplace deliveries" ON deliveries;
DROP POLICY IF EXISTS "Providers can view open marketplace package details" ON package_details;

-- 11b. Replace migration 001 "assigned OR targeted" policies with assigned-only
DROP POLICY IF EXISTS "Providers can view assigned or targeted deliveries" ON deliveries;
DROP POLICY IF EXISTS "Assigned providers can view their deliveries" ON deliveries;
CREATE POLICY "Assigned providers can view their deliveries"
  ON deliveries FOR SELECT
  TO authenticated
  USING (provider_id = auth.uid());

DROP POLICY IF EXISTS "Providers can view package details for targeted/assigned deliveries" ON package_details;
DROP POLICY IF EXISTS "Assigned providers can view package details" ON package_details;
CREATE POLICY "Assigned providers can view package details"
  ON package_details FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM deliveries d
      WHERE d.id = package_details.delivery_id AND d.provider_id = auth.uid()
    )
  );

-- 11c. Assigned-provider UPDATE: explicit WITH CHECK (columns guarded by trigger)
DROP POLICY IF EXISTS "Assigned providers can update status of assigned deliveries" ON deliveries;
CREATE POLICY "Assigned providers can update status of assigned deliveries"
  ON deliveries FOR UPDATE
  TO authenticated
  USING (provider_id = auth.uid())
  WITH CHECK (provider_id = auth.uid());

