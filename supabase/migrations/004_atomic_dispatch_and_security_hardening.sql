-- ============================================================================
-- ORDERFLOW DATABASE MIGRATION 004: ATOMIC DISPATCH & SECURITY HARDENING
-- Run this in Supabase SQL Editor AFTER migrations 001, 002 and 003.
--
-- Resolves the findings of the 19 Oct 2026 independent audit:
--   1. Dispatch RPCs did not verify the caller and could assign a delivery
--      without a valid opportunity.
--   2. Delivery creation was a sequence of non-atomic client inserts.
--   3. Marketplace RLS exposed recipient/contact PII to every provider.
--   5. decline_delivery_opportunity did not lock the delivery row.
--   6. Status transitions were not role-aware and lost caller notes.
--   7. Tracking codes had a small, collision-prone code space.
--
-- Design principles:
--   * Every dispatch mutation runs inside ONE function (= one transaction)
--     and takes a FOR UPDATE lock on the delivery row first. Acceptance,
--     decline, expiry and status transitions are therefore serialized.
--   * All authorization checks happen BEFORE any mutation.
--   * Customer PII is visible only to the vendor and the ASSIGNED provider.
--     Prospective providers see a redacted marketplace projection.
--   * Triggers enforce the same rules for direct table updates
--     (defense in depth) so the RPCs are not the only line of protection.
--
-- Session settings used internally (transaction-local, set via set_config):
--   orderflow.dispatch_context  = 'on'  -> mutation originates from a dispatch RPC
--   orderflow.transition_notes  = text  -> note recorded in delivery_status_history
-- PostgREST clients cannot set these: each request is its own transaction and
-- pg_catalog.set_config is not exposed as an RPC.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. SCHEMA ADDITIONS
-- ----------------------------------------------------------------------------

-- Idempotent creation: a retried "Confirm delivery" request with the same key
-- returns the original delivery instead of creating a duplicate.
ALTER TABLE deliveries ADD COLUMN IF NOT EXISTS idempotency_key TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS uq_deliveries_vendor_idempotency
  ON deliveries (vendor_id, idempotency_key)
  WHERE idempotency_key IS NOT NULL;

-- Offer time-to-live: a 'sent' opportunity is only acceptable until expires_at.
ALTER TABLE dispatch_opportunities ADD COLUMN IF NOT EXISTS expires_at TIMESTAMPTZ;
CREATE INDEX IF NOT EXISTS idx_dispatch_opps_sent_expiry
  ON dispatch_opportunities (expires_at)
  WHERE status = 'sent';

-- Invariant: at most ONE live ('sent') offer per delivery at any time.
-- Clean up any pre-existing violations (keep the best-ranked offer) first.
UPDATE dispatch_opportunities o
SET status = 'expired'
WHERE o.status = 'sent'
  AND EXISTS (
    SELECT 1 FROM dispatch_opportunities o2
    WHERE o2.delivery_id = o.delivery_id
      AND o2.status = 'sent'
      AND (o2.rank_order < o.rank_order OR (o2.rank_order = o.rank_order AND o2.id < o.id))
  );

CREATE UNIQUE INDEX IF NOT EXISTS uq_dispatch_opps_one_sent_per_delivery
  ON dispatch_opportunities (delivery_id)
  WHERE status = 'sent';

-- Deterministic audit ordering. Rows written in the same transaction share
-- the same NOW() value, so created_at alone cannot order them.
ALTER TABLE delivery_status_history
  ADD COLUMN IF NOT EXISTS seq BIGINT GENERATED BY DEFAULT AS IDENTITY;
CREATE INDEX IF NOT EXISTS idx_delivery_status_history_delivery_seq
  ON delivery_status_history (delivery_id, seq);


-- ----------------------------------------------------------------------------
-- 2. INTERNAL HELPERS (not callable by clients)
-- ----------------------------------------------------------------------------

-- How long a provider has to respond to a targeted offer.
CREATE OR REPLACE FUNCTION _dispatch_offer_ttl()
RETURNS INTERVAL
LANGUAGE sql
IMMUTABLE
AS $$ SELECT INTERVAL '120 seconds' $$;

-- Collision-resistant tracking code: 'OF-XXXX-XXXX' using the Crockford
-- Base32 alphabet (no I, L, O, U). 32^8 ~= 1.1 trillion combinations.
-- Randomness comes from gen_random_uuid() (CSPRNG, core since PG13); version
-- and variant bytes (6 and 8) are skipped. 256 % 32 = 0, so there is no bias.
CREATE OR REPLACE FUNCTION _generate_tracking_code()
RETURNS TEXT
LANGUAGE plpgsql
VOLATILE
AS $$
DECLARE
  v_alphabet CONSTANT TEXT := '0123456789ABCDEFGHJKMNPQRSTVWXYZ';
  v_bytes BYTEA := uuid_send(gen_random_uuid());
  v_positions CONSTANT INT[] := ARRAY[0, 1, 2, 3, 4, 5, 9, 10];
  v_code TEXT := '';
  i INT;
BEGIN
  FOR i IN 1..8 LOOP
    v_code := v_code || substr(v_alphabet, (get_byte(v_bytes, v_positions[i]) % 32) + 1, 1);
  END LOOP;
  RETURN 'OF-' || substr(v_code, 1, 4) || '-' || substr(v_code, 5, 4);
END;
$$;

-- Advances the dispatch queue for a delivery.
-- PRECONDITIONS (caller's responsibility):
--   * the caller holds a FOR UPDATE lock on the delivery row;
--   * the previously live offer (if any) is already closed.
-- Skips candidates who are currently busy/unavailable (marks them 'skipped').
-- Returns the resulting delivery status.
CREATE OR REPLACE FUNCTION _advance_dispatch_queue(p_delivery_id UUID)
RETURNS delivery_status
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_next RECORD;
  v_current delivery_status;
BEGIN
  SELECT status INTO v_current FROM deliveries WHERE id = p_delivery_id;

  PERFORM set_config('orderflow.dispatch_context', 'on', true);

  LOOP
    SELECT o.id, o.rank_order, COALESCE(pa.status, 'available') AS availability
    INTO v_next
    FROM dispatch_opportunities o
    LEFT JOIN provider_availability pa ON pa.provider_id = o.provider_id
    WHERE o.delivery_id = p_delivery_id
      AND o.status = 'queued'
    ORDER BY o.rank_order ASC
    LIMIT 1
    FOR UPDATE OF o;

    EXIT WHEN NOT FOUND;

    IF v_next.availability <> 'available' THEN
      UPDATE dispatch_opportunities
      SET status = 'skipped', responded_at = NOW()
      WHERE id = v_next.id;
      CONTINUE;
    END IF;

    UPDATE dispatch_opportunities
    SET status = 'sent', sent_at = NOW(), expires_at = NOW() + _dispatch_offer_ttl()
    WHERE id = v_next.id;

    IF v_current IS DISTINCT FROM 'opportunity_sent' THEN
      PERFORM set_config('orderflow.transition_notes',
        'Dispatch offer sent to candidate rank ' || v_next.rank_order, true);
      UPDATE deliveries SET status = 'opportunity_sent' WHERE id = p_delivery_id;
      PERFORM set_config('orderflow.transition_notes', '', true);
    END IF;

    PERFORM set_config('orderflow.dispatch_context', '', true);
    RETURN 'opportunity_sent';
  END LOOP;

  -- Queue exhausted: return the delivery to the open marketplace pool.
  IF v_current IS DISTINCT FROM 'searching' THEN
    PERFORM set_config('orderflow.transition_notes',
      'Dispatch queue exhausted; delivery returned to open marketplace', true);
    UPDATE deliveries SET status = 'searching' WHERE id = p_delivery_id;
    PERFORM set_config('orderflow.transition_notes', '', true);
  END IF;

  PERFORM set_config('orderflow.dispatch_context', '', true);
  RETURN 'searching';
END;
$$;

-- Builds the JSON payload returned by create_delivery_transactional.
CREATE OR REPLACE FUNCTION _delivery_creation_payload(p_delivery_id UUID, p_replay BOOLEAN)
RETURNS JSONB
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT jsonb_build_object(
    'success', true,
    'idempotent_replay', p_replay,
    'delivery_id', d.id,
    'tracking_code', d.tracking_code,
    'status', d.status,
    'provider_id', d.provider_id,
    'current_opportunity_provider_id', (
      SELECT o.provider_id FROM dispatch_opportunities o
      WHERE o.delivery_id = d.id AND o.status = 'sent'
      LIMIT 1
    ),
    'candidate_provider_ids', COALESCE((
      SELECT jsonb_agg(o.provider_id ORDER BY o.rank_order)
      FROM dispatch_opportunities o
      WHERE o.delivery_id = d.id
    ), '[]'::jsonb),
    'created_at', d.created_at,
    'updated_at', d.updated_at
  )
  FROM deliveries d
  WHERE d.id = p_delivery_id;
$$;

