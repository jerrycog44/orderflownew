-- ----------------------------------------------------------------------------
-- 3. ROLE-AWARE STATUS STATE MACHINE (replaces migration 003 trigger body)
-- ----------------------------------------------------------------------------
-- Transition matrix is unchanged from 003. New:
--   * Actor rules (who may move a delivery into each status).
--   * Notes from orderflow.transition_notes are recorded in the audit row.
-- auth.uid() IS NULL means a trusted server context (service_role, SQL editor,
-- scheduled jobs), which is allowed to perform any VALID transition.

CREATE OR REPLACE FUNCTION validate_delivery_status_transition()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor UUID := auth.uid();
  v_dispatch BOOLEAN := COALESCE(current_setting('orderflow.dispatch_context', true), '') = 'on';
  v_notes TEXT := NULLIF(current_setting('orderflow.transition_notes', true), '');
BEGIN
  IF OLD.status = NEW.status THEN
    RETURN NEW;
  END IF;

  IF OLD.status = 'delivered' THEN
    RAISE EXCEPTION 'Cannot modify status of a delivery that is already delivered';
  END IF;

  IF OLD.status = 'cancelled' THEN
    RAISE EXCEPTION 'Cannot modify status of a delivery that is cancelled';
  END IF;

  -- 3a. Transition matrix
  CASE OLD.status
    WHEN 'draft' THEN
      IF NEW.status NOT IN ('created', 'searching', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'created' THEN
      IF NEW.status NOT IN ('searching', 'opportunity_sent', 'provider_selected', 'awaiting_pickup', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'searching' THEN
      IF NEW.status NOT IN ('opportunity_sent', 'provider_selected', 'awaiting_pickup', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'opportunity_sent' THEN
      IF NEW.status NOT IN ('provider_selected', 'awaiting_pickup', 'searching', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'provider_selected' THEN
      IF NEW.status NOT IN ('awaiting_pickup', 'picked_up', 'in_transit', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'awaiting_pickup' THEN
      IF NEW.status NOT IN ('picked_up', 'in_transit', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'picked_up' THEN
      IF NEW.status NOT IN ('in_transit', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    WHEN 'in_transit' THEN
      IF NEW.status NOT IN ('delivered', 'cancelled') THEN
        RAISE EXCEPTION 'Invalid transition from % to %', OLD.status, NEW.status;
      END IF;
    ELSE
      RAISE EXCEPTION 'Unknown previous delivery status %', OLD.status;
  END CASE;

  -- 3b. Actor rules (skipped for trusted server contexts)
  IF v_actor IS NOT NULL THEN
    IF NEW.status IN ('searching', 'opportunity_sent', 'provider_selected') THEN
      IF NOT v_dispatch THEN
        RAISE EXCEPTION 'Status % can only be set by the dispatch engine', NEW.status
          USING ERRCODE = '42501';
      END IF;

    ELSIF NEW.status IN ('awaiting_pickup', 'picked_up', 'in_transit', 'delivered') THEN
      IF OLD.provider_id IS NULL
         OR v_actor IS DISTINCT FROM OLD.provider_id
         OR NEW.provider_id IS DISTINCT FROM OLD.provider_id THEN
        RAISE EXCEPTION 'Only the assigned provider can move a delivery to %', NEW.status
          USING ERRCODE = '42501';
      END IF;

    ELSIF NEW.status = 'cancelled' THEN
      IF NOT v_dispatch THEN
        IF v_actor IS DISTINCT FROM OLD.vendor_id THEN
          RAISE EXCEPTION 'Only the vendor can cancel a delivery'
            USING ERRCODE = '42501';
        END IF;
        IF OLD.status IN ('picked_up', 'in_transit') THEN
          RAISE EXCEPTION 'A delivery cannot be cancelled after pickup'
            USING ERRCODE = '42501';
        END IF;
      END IF;

    ELSIF NEW.status = 'created' THEN
      IF v_actor IS DISTINCT FROM OLD.vendor_id THEN
        RAISE EXCEPTION 'Only the vendor can submit a draft delivery'
          USING ERRCODE = '42501';
      END IF;
    END IF;
  END IF;

  -- 3c. Single, authoritative audit entry for every status change
  INSERT INTO delivery_status_history (
    delivery_id, previous_status, new_status, changed_by_user_id, notes
  ) VALUES (
    NEW.id,
    OLD.status,
    NEW.status,
    v_actor,
    COALESCE(v_notes, 'Status transitioned from ' || OLD.status || ' to ' || NEW.status)
  );

  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION validate_delivery_status_transition() FROM PUBLIC, anon, authenticated;

-- Trigger definition from 003 already points at this function; recreate to be explicit.
DROP TRIGGER IF EXISTS trg_validate_delivery_status_transition ON deliveries;
CREATE TRIGGER trg_validate_delivery_status_transition
  BEFORE UPDATE OF status ON deliveries
  FOR EACH ROW
  EXECUTE FUNCTION validate_delivery_status_transition();


-- ----------------------------------------------------------------------------
-- 4. COLUMN GUARD TRIGGER (defense in depth for direct UPDATEs)
-- ----------------------------------------------------------------------------
-- RLS decides WHICH rows a user may update; this trigger decides WHAT they may
-- change. Fires before trg_validate_* (triggers run in name order).

CREATE OR REPLACE FUNCTION guard_delivery_column_changes()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_actor UUID := auth.uid();
  v_dispatch BOOLEAN := COALESCE(current_setting('orderflow.dispatch_context', true), '') = 'on';
BEGIN
  IF v_actor IS NULL THEN
    RETURN NEW; -- trusted server context
  END IF;

  IF NEW.vendor_id IS DISTINCT FROM OLD.vendor_id
     OR NEW.tracking_code IS DISTINCT FROM OLD.tracking_code
     OR NEW.idempotency_key IS DISTINCT FROM OLD.idempotency_key
     OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
    RAISE EXCEPTION 'vendor_id, tracking_code, idempotency_key and created_at are immutable'
      USING ERRCODE = '42501';
  END IF;

  IF NEW.provider_id IS DISTINCT FROM OLD.provider_id AND NOT v_dispatch THEN
    RAISE EXCEPTION 'provider_id can only be changed by the dispatch engine'
      USING ERRCODE = '42501';
  END IF;

  -- An assigned provider may only change status and driver assignment.
  IF v_actor = OLD.provider_id AND v_actor IS DISTINCT FROM OLD.vendor_id AND NOT v_dispatch THEN
    IF (to_jsonb(NEW) - 'status' - 'driver_id' - 'updated_at')
       IS DISTINCT FROM (to_jsonb(OLD) - 'status' - 'driver_id' - 'updated_at') THEN
      RAISE EXCEPTION 'Assigned providers may only update status and driver assignment'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  -- A driver must belong to the delivery's provider fleet.
  IF NEW.driver_id IS NOT NULL AND NEW.driver_id IS DISTINCT FROM OLD.driver_id THEN
    IF NOT EXISTS (
      SELECT 1 FROM drivers dr
      WHERE dr.id = NEW.driver_id AND dr.provider_id = NEW.provider_id AND dr.is_active
    ) THEN
      RAISE EXCEPTION 'Driver does not belong to the assigned provider fleet'
        USING ERRCODE = '42501';
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

REVOKE EXECUTE ON FUNCTION guard_delivery_column_changes() FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS trg_guard_delivery_column_changes ON deliveries;
CREATE TRIGGER trg_guard_delivery_column_changes
  BEFORE UPDATE ON deliveries
  FOR EACH ROW
  EXECUTE FUNCTION guard_delivery_column_changes();


-- ----------------------------------------------------------------------------
-- 5. SECURED, SERIALIZED ACCEPTANCE RPC (replaces migration 003 version)
-- ----------------------------------------------------------------------------
-- Accepts EITHER:
--   (a) a live targeted offer: delivery 'opportunity_sent' AND the caller holds
--       the 'sent', unexpired opportunity; OR
--   (b) an open-pool claim: delivery 'searching'/'created' with no provider
--       (queue exhausted or never matched). The caller must be available.
-- Every check runs after the row lock and before any mutation.
-- Error codes: not_authenticated, forbidden, not_a_provider, not_found,
--   already_assigned, no_active_offer, offer_expired, provider_unavailable,
--   not_available.

CREATE OR REPLACE FUNCTION accept_delivery_opportunity(
  p_delivery_id UUID,
  p_provider_id UUID
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller UUID := auth.uid();
  v_delivery RECORD;
  v_opp RECORD;
  v_availability availability_status;
BEGIN
  -- 1. Identity
  IF v_caller IS NULL THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_authenticated',
      'error', 'Authentication required');
  END IF;

  IF p_provider_id IS DISTINCT FROM v_caller THEN
    RETURN jsonb_build_object('success', false, 'code', 'forbidden',
      'error', 'You can only accept deliveries on behalf of your own provider account');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM logistics_providers WHERE id = v_caller) THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_a_provider',
      'error', 'Only registered logistics providers can accept deliveries');
  END IF;

  -- 2. Serialize on the delivery row
  SELECT * INTO v_delivery FROM deliveries WHERE id = p_delivery_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_found',
      'error', 'Delivery not found');
  END IF;

  -- 3. Already assigned? (idempotent for the same provider)
  IF v_delivery.provider_id IS NOT NULL THEN
    IF v_delivery.provider_id = v_caller
       AND v_delivery.status NOT IN ('delivered', 'cancelled') THEN
      RETURN jsonb_build_object('success', true, 'already_accepted', true,
        'delivery_id', p_delivery_id, 'status', v_delivery.status);
    END IF;
    RETURN jsonb_build_object('success', false, 'code', 'already_assigned',
      'error', 'Delivery has already been assigned to another provider');
  END IF;

  SELECT * INTO v_opp
  FROM dispatch_opportunities
  WHERE delivery_id = p_delivery_id AND provider_id = v_caller
  FOR UPDATE;

  -- 4. Eligibility
  IF v_delivery.status = 'opportunity_sent' THEN
    IF v_opp.id IS NULL OR v_opp.status <> 'sent' THEN
      RETURN jsonb_build_object('success', false, 'code', 'no_active_offer',
        'error', 'This delivery is currently offered to another provider');
    END IF;

    IF v_opp.expires_at IS NOT NULL AND v_opp.expires_at <= NOW() THEN
      -- Maintain queue state while we hold the lock, then reject.
      UPDATE dispatch_opportunities
      SET status = 'expired', responded_at = NOW()
      WHERE id = v_opp.id;
      PERFORM _advance_dispatch_queue(p_delivery_id);
      RETURN jsonb_build_object('success', false, 'code', 'offer_expired',
        'error', 'This offer has expired');
    END IF;

  ELSIF v_delivery.status IN ('searching', 'created') THEN
    SELECT status INTO v_availability FROM provider_availability WHERE provider_id = v_caller;
    IF COALESCE(v_availability, 'available') <> 'available' THEN
      RETURN jsonb_build_object('success', false, 'code', 'provider_unavailable',
        'error', 'Set your availability to Available before claiming open deliveries');
    END IF;

  ELSE
    RETURN jsonb_build_object('success', false, 'code', 'not_available',
      'error', 'Delivery is no longer available (current status: ' || v_delivery.status || ')');
  END IF;

  -- 5. Mutations (all checks passed)
  PERFORM set_config('orderflow.dispatch_context', 'on', true);
  PERFORM set_config('orderflow.transition_notes',
    CASE WHEN v_delivery.status = 'opportunity_sent'
      THEN 'Targeted dispatch offer accepted by provider'
      ELSE 'Open marketplace delivery claimed by provider' END, true);

  UPDATE deliveries
  SET provider_id = v_caller, status = 'provider_selected'
  WHERE id = p_delivery_id;

  IF v_opp.id IS NOT NULL THEN
    UPDATE dispatch_opportunities
    SET status = 'accepted', responded_at = NOW()
    WHERE id = v_opp.id;
  ELSE
    INSERT INTO dispatch_opportunities (delivery_id, provider_id, rank_order, status, sent_at, responded_at)
    VALUES (
      p_delivery_id, v_caller,
      COALESCE((SELECT MAX(rank_order) FROM dispatch_opportunities WHERE delivery_id = p_delivery_id), 0) + 1,
      'accepted', NOW(), NOW()
    );
  END IF;

  UPDATE dispatch_opportunities
  SET status = 'expired', responded_at = COALESCE(responded_at, NOW())
  WHERE delivery_id = p_delivery_id
    AND provider_id <> v_caller
    AND status IN ('queued', 'sent');

  PERFORM set_config('orderflow.transition_notes', '', true);
  PERFORM set_config('orderflow.dispatch_context', '', true);

  RETURN jsonb_build_object('success', true, 'already_accepted', false,
    'delivery_id', p_delivery_id, 'status', 'provider_selected');
END;
$$;

REVOKE EXECUTE ON FUNCTION accept_delivery_opportunity(UUID, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION accept_delivery_opportunity(UUID, UUID) TO authenticated;


-- ----------------------------------------------------------------------------
-- 6. SECURED, SERIALIZED DECLINE RPC (replaces migration 003 version)
-- ----------------------------------------------------------------------------
-- Error codes: not_authenticated, forbidden, not_found, not_available,
--   no_active_offer.

CREATE OR REPLACE FUNCTION decline_delivery_opportunity(
  p_delivery_id UUID,
  p_provider_id UUID
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller UUID := auth.uid();
  v_delivery RECORD;
  v_opp RECORD;
  v_new_status delivery_status;
BEGIN
  IF v_caller IS NULL THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_authenticated',
      'error', 'Authentication required');
  END IF;

  IF p_provider_id IS DISTINCT FROM v_caller THEN
    RETURN jsonb_build_object('success', false, 'code', 'forbidden',
      'error', 'You can only decline offers sent to your own provider account');
  END IF;

  -- Serialize with concurrent accept / decline / expiry on the same delivery
  SELECT * INTO v_delivery FROM deliveries WHERE id = p_delivery_id FOR UPDATE;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_found',
      'error', 'Delivery not found');
  END IF;

  IF v_delivery.status <> 'opportunity_sent' OR v_delivery.provider_id IS NOT NULL THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_available',
      'error', 'Delivery is not awaiting a response (current status: ' || v_delivery.status || ')');
  END IF;

  SELECT * INTO v_opp
  FROM dispatch_opportunities
  WHERE delivery_id = p_delivery_id AND provider_id = v_caller
  FOR UPDATE;

  IF v_opp.id IS NULL OR v_opp.status <> 'sent' THEN
    RETURN jsonb_build_object('success', false, 'code', 'no_active_offer',
      'error', 'You do not hold an active offer for this delivery');
  END IF;

  UPDATE dispatch_opportunities
  SET status = 'declined', responded_at = NOW()
  WHERE id = v_opp.id;

  v_new_status := _advance_dispatch_queue(p_delivery_id);

  RETURN jsonb_build_object('success', true,
    'delivery_id', p_delivery_id, 'status', v_new_status);
END;
$$;

REVOKE EXECUTE ON FUNCTION decline_delivery_opportunity(UUID, UUID) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION decline_delivery_opportunity(UUID, UUID) TO authenticated;


-- ----------------------------------------------------------------------------
-- 7. OFFER EXPIRY SWEEP (server-side only)
-- ----------------------------------------------------------------------------
-- Expires 'sent' offers past expires_at and advances each queue exactly once.
-- SKIP LOCKED: deliveries currently being accepted/declined are left for the
-- next sweep instead of blocking. Schedule with pg_cron (if enabled), e.g.:
--   SELECT cron.schedule('orderflow-expire-offers', '* * * * *',
--                        $$SELECT public.expire_stale_dispatch_opportunities()$$);

CREATE OR REPLACE FUNCTION expire_stale_dispatch_opportunities()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_row RECORD;
  v_count INTEGER := 0;
BEGIN
  FOR v_row IN
    SELECT d.id AS delivery_id
    FROM deliveries d
    WHERE d.status = 'opportunity_sent'
      AND d.provider_id IS NULL
      AND EXISTS (
        SELECT 1 FROM dispatch_opportunities o
        WHERE o.delivery_id = d.id AND o.status = 'sent' AND o.expires_at <= NOW()
      )
    FOR UPDATE OF d SKIP LOCKED
  LOOP
    UPDATE dispatch_opportunities
    SET status = 'expired', responded_at = NOW()
    WHERE delivery_id = v_row.delivery_id AND status = 'sent' AND expires_at <= NOW();

    PERFORM _advance_dispatch_queue(v_row.delivery_id);
    v_count := v_count + 1;
  END LOOP;

  RETURN v_count;
END;
$$;

REVOKE EXECUTE ON FUNCTION expire_stale_dispatch_opportunities() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION expire_stale_dispatch_opportunities() TO service_role;


-- ----------------------------------------------------------------------------
-- 8. ROLE-AWARE STATUS TRANSITION RPC
-- ----------------------------------------------------------------------------
-- Single entry point for lifecycle updates (pickup, transit, delivered,
-- cancel). Records the caller and an optional note in one audit row — the
-- client must NOT insert into delivery_status_history itself.
-- Dispatch statuses must go through accept/decline instead.
-- Error codes: not_authenticated, not_found, use_dispatch_rpc, forbidden,
--   invalid_transition.

CREATE OR REPLACE FUNCTION transition_delivery_status(
  p_delivery_id UUID,
  p_new_status delivery_status,
  p_notes TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller UUID := auth.uid();
  v_delivery RECORD;
BEGIN
  IF v_caller IS NULL THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_authenticated',
      'error', 'Authentication required');
  END IF;

  SELECT * INTO v_delivery FROM deliveries WHERE id = p_delivery_id FOR UPDATE;

  -- Do not reveal the existence of deliveries the caller is not party to.
  IF NOT FOUND OR (v_caller IS DISTINCT FROM v_delivery.vendor_id
                   AND v_caller IS DISTINCT FROM v_delivery.provider_id) THEN
    RETURN jsonb_build_object('success', false, 'code', 'not_found',
      'error', 'Delivery not found');
  END IF;

  IF p_new_status IN ('draft', 'created', 'searching', 'opportunity_sent', 'provider_selected') THEN
    RETURN jsonb_build_object('success', false, 'code', 'use_dispatch_rpc',
      'error', 'Status ' || p_new_status || ' is managed by the dispatch engine');
  END IF;

  IF v_delivery.status = p_new_status THEN
    RETURN jsonb_build_object('success', true, 'unchanged', true,
      'delivery_id', p_delivery_id, 'status', p_new_status);
  END IF;

  PERFORM set_config('orderflow.transition_notes', COALESCE(left(btrim(p_notes), 500), ''), true);

  BEGIN
    UPDATE deliveries SET status = p_new_status WHERE id = p_delivery_id;

    -- A cancelled delivery must not leave live or queued offers behind.
    IF p_new_status = 'cancelled' THEN
      UPDATE dispatch_opportunities
      SET status = 'expired', responded_at = COALESCE(responded_at, NOW())
      WHERE delivery_id = p_delivery_id AND status IN ('queued', 'sent');
    END IF;
  EXCEPTION
    WHEN insufficient_privilege THEN
      PERFORM set_config('orderflow.transition_notes', '', true);
      RETURN jsonb_build_object('success', false, 'code', 'forbidden', 'error', SQLERRM);
    WHEN raise_exception THEN
      PERFORM set_config('orderflow.transition_notes', '', true);
      RETURN jsonb_build_object('success', false, 'code', 'invalid_transition', 'error', SQLERRM);
  END;

  PERFORM set_config('orderflow.transition_notes', '', true);

  RETURN jsonb_build_object('success', true, 'unchanged', false,
    'delivery_id', p_delivery_id, 'status', p_new_status);
END;
$$;

REVOKE EXECUTE ON FUNCTION transition_delivery_status(UUID, delivery_status, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION transition_delivery_status(UUID, delivery_status, TEXT) TO authenticated;


-- ----------------------------------------------------------------------------
-- 9. ATOMIC DELIVERY CREATION RPC
-- ----------------------------------------------------------------------------
-- Creates delivery + package details + dispatch queue + audit trail in ONE
-- transaction. Any failure (constraint, invalid enum, bad provider, ...) rolls
-- back everything: no orphaned deliveries, no missing package rows.
--
-- Auto mode : p_candidate_provider_ids is the ranked shortlist from the
--             recommendation engine. Unknown IDs are dropped, duplicates
--             removed, busy/unavailable candidates skipped at offer time.
-- Manual    : p_selected_provider_id is assigned directly ('awaiting_pickup'),
--             matching existing product behaviour.
-- Idempotent: passing the same p_idempotency_key again returns the original
--             delivery with idempotent_replay = true.

CREATE OR REPLACE FUNCTION create_delivery_transactional(
  p_pickup_address TEXT,
  p_pickup_city TEXT,
  p_destination_address TEXT,
  p_destination_city TEXT,
  p_recipient_name TEXT,
  p_recipient_phone TEXT,
  p_estimated_price NUMERIC,
  p_dispatch_mode dispatch_mode_enum,
  p_product_name TEXT,
  p_item_category TEXT,
  p_package_type package_type_enum,
  p_weight_kg NUMERIC,
  p_quantity INTEGER DEFAULT 1,
  p_length_cm NUMERIC DEFAULT NULL,
  p_width_cm NUMERIC DEFAULT NULL,
  p_height_cm NUMERIC DEFAULT NULL,
  p_is_fragile BOOLEAN DEFAULT FALSE,
  p_image_url TEXT DEFAULT NULL,
  p_special_instructions TEXT DEFAULT NULL,
  p_pickup_contact_name TEXT DEFAULT NULL,
  p_pickup_contact_phone TEXT DEFAULT NULL,
  p_delivery_notes TEXT DEFAULT NULL,
  p_estimated_delivery_time TEXT DEFAULT NULL,
  p_selected_provider_id UUID DEFAULT NULL,
  p_candidate_provider_ids UUID[] DEFAULT NULL,
  p_idempotency_key TEXT DEFAULT NULL
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_caller UUID := auth.uid();
  v_existing_id UUID;
  v_delivery_id UUID;
  v_code TEXT;
  v_constraint TEXT;
  v_key TEXT := NULLIF(btrim(p_idempotency_key), '');
  v_status delivery_status;
  v_provider UUID;
  v_candidates UUID[];
  v_availability availability_status;
  v_attempt INT;
BEGIN
  -- 1. Identity
  IF v_caller IS NULL THEN
    RAISE EXCEPTION 'Authentication required' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (SELECT 1 FROM vendors WHERE id = v_caller) THEN
    RAISE EXCEPTION 'Only registered vendors can create deliveries' USING ERRCODE = '42501';
  END IF;

  -- 2. Idempotent replay (fast path)
  IF v_key IS NOT NULL THEN
    SELECT id INTO v_existing_id FROM deliveries
    WHERE vendor_id = v_caller AND idempotency_key = v_key;
    IF FOUND THEN
      RETURN _delivery_creation_payload(v_existing_id, true);
    END IF;
  END IF;

  -- 3. Input validation (table CHECK constraints cover numeric ranges)
  IF NULLIF(btrim(p_pickup_address), '') IS NULL
     OR NULLIF(btrim(p_pickup_city), '') IS NULL
     OR NULLIF(btrim(p_destination_address), '') IS NULL
     OR NULLIF(btrim(p_destination_city), '') IS NULL
     OR NULLIF(btrim(p_recipient_name), '') IS NULL
     OR NULLIF(btrim(p_recipient_phone), '') IS NULL
     OR NULLIF(btrim(p_product_name), '') IS NULL
     OR NULLIF(btrim(p_item_category), '') IS NULL THEN
    RAISE EXCEPTION 'Missing required delivery fields' USING ERRCODE = '22023';
  END IF;

  -- 4. Resolve dispatch plan
  IF p_dispatch_mode = 'manual' THEN
    IF p_selected_provider_id IS NULL
       OR NOT EXISTS (SELECT 1 FROM logistics_providers WHERE id = p_selected_provider_id) THEN
      RAISE EXCEPTION 'Manual dispatch requires a valid selected provider' USING ERRCODE = '22023';
    END IF;
    SELECT status INTO v_availability FROM provider_availability WHERE provider_id = p_selected_provider_id;
    IF COALESCE(v_availability, 'available') = 'unavailable' THEN
      RAISE EXCEPTION 'Selected provider is currently unavailable' USING ERRCODE = '22023';
    END IF;
    v_provider := p_selected_provider_id;
    v_status := 'awaiting_pickup';
  ELSE
    -- Deduplicate (keep first occurrence = best rank) and drop unknown providers.
    SELECT COALESCE(array_agg(c.pid ORDER BY c.first_pos), '{}')
    INTO v_candidates
    FROM (
      SELECT u.pid, MIN(u.pos) AS first_pos
      FROM unnest(COALESCE(p_candidate_provider_ids, '{}'::UUID[])) WITH ORDINALITY AS u(pid, pos)
      JOIN logistics_providers lp ON lp.id = u.pid
      GROUP BY u.pid
    ) c;
    v_provider := NULL;
    v_status := 'searching'; -- promoted to 'opportunity_sent' by the queue below
  END IF;

  -- 5. Insert delivery with a unique tracking code (retry on collision)
  FOR v_attempt IN 1..5 LOOP
    v_code := _generate_tracking_code();
    BEGIN
      INSERT INTO deliveries (
        tracking_code, vendor_id, provider_id, status, dispatch_mode,
        pickup_address, pickup_city, pickup_contact_name, pickup_contact_phone,
        destination_address, destination_city, recipient_name, recipient_phone,
        delivery_notes, estimated_price, estimated_delivery_time, idempotency_key
      ) VALUES (
        v_code, v_caller, v_provider, v_status, p_dispatch_mode,
        btrim(p_pickup_address), btrim(p_pickup_city),
        NULLIF(btrim(p_pickup_contact_name), ''), NULLIF(btrim(p_pickup_contact_phone), ''),
        btrim(p_destination_address), btrim(p_destination_city),
        btrim(p_recipient_name), btrim(p_recipient_phone),
        NULLIF(btrim(p_delivery_notes), ''), p_estimated_price,
        COALESCE(NULLIF(btrim(p_estimated_delivery_time), ''), 'Same Day'), v_key
      )
      RETURNING id INTO v_delivery_id;
      EXIT;
    EXCEPTION WHEN unique_violation THEN
      GET STACKED DIAGNOSTICS v_constraint = CONSTRAINT_NAME;
      IF v_constraint = 'uq_deliveries_vendor_idempotency' THEN
        -- A concurrent request with the same key won the race.
        SELECT id INTO v_existing_id FROM deliveries
        WHERE vendor_id = v_caller AND idempotency_key = v_key;
        RETURN _delivery_creation_payload(v_existing_id, true);
      ELSIF v_constraint = 'deliveries_tracking_code_key' AND v_attempt < 5 THEN
        CONTINUE;
      ELSE
        RAISE;
      END IF;
    END;
  END LOOP;

  -- 6. Package details (failure here rolls back the delivery as well)
  INSERT INTO package_details (
    delivery_id, product_name, item_category, package_type, quantity, weight_kg,
    length_cm, width_cm, height_cm, is_fragile, image_url, special_instructions
  ) VALUES (
    v_delivery_id, btrim(p_product_name), btrim(p_item_category), p_package_type,
    COALESCE(p_quantity, 1), p_weight_kg,
    p_length_cm, p_width_cm, p_height_cm, COALESCE(p_is_fragile, FALSE),
    NULLIF(btrim(p_image_url), ''), NULLIF(btrim(p_special_instructions), '')
  );

  -- 7. Creation audit entry (INSERTs do not fire the status trigger)
  INSERT INTO delivery_status_history (delivery_id, previous_status, new_status, changed_by_user_id, notes)
  VALUES (v_delivery_id, NULL, v_status, v_caller, 'Delivery order created');

  -- 8. Dispatch queue (auto mode)
  IF p_dispatch_mode = 'auto' AND cardinality(v_candidates) > 0 THEN
    INSERT INTO dispatch_opportunities (delivery_id, provider_id, rank_order, status)
    SELECT v_delivery_id, c.pid, c.pos::INT, 'queued'
    FROM unnest(v_candidates) WITH ORDINALITY AS c(pid, pos);

    PERFORM _advance_dispatch_queue(v_delivery_id);
  END IF;

  RETURN _delivery_creation_payload(v_delivery_id, false);
END;
$$;

REVOKE EXECUTE ON FUNCTION create_delivery_transactional(
  TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, NUMERIC, dispatch_mode_enum, TEXT, TEXT,
  package_type_enum, NUMERIC, INTEGER, NUMERIC, NUMERIC, NUMERIC, BOOLEAN, TEXT,
  TEXT, TEXT, TEXT, TEXT, TEXT, UUID, UUID[], TEXT
) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION create_delivery_transactional(
  TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, NUMERIC, dispatch_mode_enum, TEXT, TEXT,
  package_type_enum, NUMERIC, INTEGER, NUMERIC, NUMERIC, NUMERIC, BOOLEAN, TEXT,
  TEXT, TEXT, TEXT, TEXT, TEXT, UUID, UUID[], TEXT
) TO authenticated;


-- ----------------------------------------------------------------------------
-- 10. REDACTED MARKETPLACE PROJECTION
-- ----------------------------------------------------------------------------
-- What a provider needs to decide whether to accept — and nothing more.
-- EXCLUDED until assignment: street addresses, recipient name/phone,
-- pickup contact name/phone, delivery notes, special instructions, image.
-- Returns:
--   * the caller's live targeted offer(s) (regardless of coverage area), and
--   * open-pool deliveries ('searching'/'created', unassigned), optionally
--     filtered by coverage area (matches pickup or destination city).

CREATE OR REPLACE FUNCTION get_marketplace_opportunities(p_coverage_area TEXT DEFAULT NULL)
RETURNS TABLE (
  delivery_id UUID,
  tracking_code TEXT,
  status delivery_status,
  dispatch_mode dispatch_mode_enum,
  pickup_city TEXT,
  destination_city TEXT,
  item_category TEXT,
  package_type package_type_enum,
  quantity INTEGER,
  weight_kg NUMERIC,
  length_cm NUMERIC,
  width_cm NUMERIC,
  height_cm NUMERIC,
  is_fragile BOOLEAN,
  estimated_price NUMERIC,
  estimated_delivery_time TEXT,
  vendor_name TEXT,
  is_targeted_offer BOOLEAN,
  offer_expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    d.id, d.tracking_code, d.status, d.dispatch_mode,
    d.pickup_city, d.destination_city,
    p.item_category, p.package_type, p.quantity, p.weight_kg,
    p.length_cm, p.width_cm, p.height_cm, p.is_fragile,
    d.estimated_price, d.estimated_delivery_time,
    v.business_name,
    (o.status = 'sent') IS TRUE AS is_targeted_offer,
    CASE WHEN o.status = 'sent' THEN o.expires_at END,
    d.created_at
  FROM deliveries d
  JOIN package_details p ON p.delivery_id = d.id
  JOIN vendors v ON v.id = d.vendor_id
  LEFT JOIN dispatch_opportunities o
    ON o.delivery_id = d.id AND o.provider_id = auth.uid()
  WHERE EXISTS (SELECT 1 FROM logistics_providers lp WHERE lp.id = auth.uid())
    AND d.provider_id IS NULL
    AND (
      (d.status = 'opportunity_sent'
        AND o.status = 'sent'
        AND (o.expires_at IS NULL OR o.expires_at > NOW()))
      OR
      (d.status IN ('searching', 'created')
        AND (NULLIF(btrim(p_coverage_area), '') IS NULL
             OR strpos(lower(d.pickup_city), lower(btrim(p_coverage_area))) > 0
             OR strpos(lower(d.destination_city), lower(btrim(p_coverage_area))) > 0))
    )
  ORDER BY (o.status = 'sent') IS TRUE DESC, d.created_at DESC
  LIMIT 100;
$$;

REVOKE EXECUTE ON FUNCTION get_marketplace_opportunities(TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION get_marketplace_opportunities(TEXT) TO authenticated;


